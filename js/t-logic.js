reg('logic', 'log_proof', d => {
  if (d === 3 || R.chance(0.4)) {
    const items = [
      ['Все числа, оканчивающиеся на 5, нечётные.', 'общее', 'Общее утверждение («все») доказывают рассуждением, а опровергают одним контрпримером.'],
      ['Существует двузначное число, которое делится на 13.', 'существование', 'Утверждение о существовании доказывают одним примером: 26.'],
      ['Хотя бы одно из чисел 21, 35, 49 делится на 7.', 'существование', '«Хотя бы одно» — достаточно одного примера: 21 = 7 · 3.'],
      ['Каждое чётное число делится на 2.', 'общее', '«Каждое» — общее утверждение.'],
      ['Некоторые прямоугольники — квадраты.', 'существование', '«Некоторые» = «существуют» — достаточно примера.'],
      ['Любое натуральное число больше нуля.', 'общее', '«Любое» — общее утверждение.']
    ];
    const [s, kind, why] = R.pick(items);
    const opts = ['Общее утверждение', 'Утверждение о существовании'];
    return { q: `Какое это утверждение?<br><b>«${s}»</b>`, type: 'choice', options: opts, answer: kind === 'общее' ? opts[0] : opts[1],
      hint: 'Слова «все, каждый, любой» — общее. Слова «существует, хотя бы один, некоторые» — о существовании.', explain: [why] };
  }
  for (let t = 0; t < 50; t++) {
    const a = R.pick([3, 4, 6, 7, 9, 11]), b = R.pick([2, 3, 4, 5]); if (a === b || a % b === 0 || b % a === 0) continue;
    const l = a * b / gcd(a, b);
    if (l > 99) continue;
    const right = l * R.int(1, Math.floor(99 / l));
    const dis = R.shuffle([right + a, right - b, a * 10 + 1, b * 7 + 1, right + 1].filter(n => n > 0 && !(n % a === 0 && n % b === 0)));
    return { q: `Как доказать, что <b>существует</b> число, которое делится и на ${a}, и на ${b}?<br>Выбери пример:`, type: 'choice',
      options: choices(right, dis), answer: fmt(right), hint: `Проверь каждое число: делится ли оно и на ${a}, и на ${b}?`,
      explain: ['Утверждение о существовании доказывают одним примером.', `${right} = ${a} · ${right / a} и ${right} = ${b} · ${right / b} ✓`] };
  }
  return null;
});
