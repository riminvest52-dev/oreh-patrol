reg('logic', 'log_tf', d => {
  if (d === 1) {
    const [s, v, why] = R.pick(BANK_STMT);
    const right = v ? 'Да, это высказывание' : 'Нет, не высказывание';
    return { q: `Является ли предложение высказыванием?<br><b>«${s}»</b>`, type: 'choice', options: ['Да, это высказывание', 'Нет, не высказывание'], answer: right,
      hint: 'Высказывание — это утверждение, про которое можно сказать: истинно оно или ложно.', explain: ['Высказывание — утверждение, которое либо истинно, либо ложно.', why] };
  }
  if (d === 2 || R.chance(0.3)) {
    const [s, v, why] = R.pick(BANK_TF);
    return { q: `Истинно или ложно?<br><b>«${s}»</b>`, type: 'choice', options: TF, answer: v ? TF[0] : TF[1],
      hint: 'Общее утверждение («все», «любой», «каждый») ложно, если есть хотя бы один контрпример.', explain: [why] };
  }
  const nums = R.sample(Array.from({ length: 90 }, (_, i) => i + 10), 4).sort((a, b) => a - b);
  const P = R.pick(PROPS);
  const holds = nums.filter(P.t);
  if (R.chance(0.5)) {
    const v = holds.length === nums.length;
    const bad = nums.find(n => !P.t(n));
    return { q: `Истинно или ложно?<br><b>«Все числа ${nums.join(', ')} ${/^(чёт|нечёт|двузн)/.test(P.s) ? '— ' : ''}${P.s}»</b>`, type: 'choice', options: TF, answer: v ? TF[0] : TF[1],
      hint: '«Все» — значит, надо проверить КАЖДОЕ число.', explain: v ? ['Проверяем каждое: ' + nums.map(P.why).join('; ') + '. Истинно.'] : [`Контрпример: ${bad} — не подходит. Значит, ложно.`] };
  }
  const v = holds.length > 0;
  return { q: `Истинно или ложно?<br><b>«Хотя бы одно из чисел ${nums.join(', ')} ${/^(чёт|нечёт|двузн)/.test(P.s) ? '— ' : ''}${P.one}»</b>`,
    type: 'choice', options: TF, answer: v ? TF[0] : TF[1], hint: '«Хотя бы одно» — достаточно найти один пример.',
    explain: v ? [`Пример: ${P.why(holds[0])}. Одного примера достаточно — истинно.`] : ['Ни одно число не подходит — значит, ложно.'] };
});

/* Контрпример к «Все числа, которые …, …» */
const IMPL = [
  { a: 'делятся на 3', b: 'делятся на 6', A: n => n % 3 === 0, B: n => n % 6 === 0 },
  { a: 'делятся на 2', b: 'делятся на 4', A: n => n % 2 === 0, B: n => n % 4 === 0 },
  { a: 'оканчиваются на 4', b: 'делятся на 4', A: n => n % 10 === 4, B: n => n % 4 === 0 },
  { a: 'делятся на 5', b: 'делятся на 10', A: n => n % 5 === 0, B: n => n % 10 === 0 },
  { a: 'больше 20', b: 'больше 30', A: n => n > 20, B: n => n > 30 },
  { a: 'делятся на 4', b: 'делятся на 8', A: n => n % 4 === 0, B: n => n % 8 === 0 },
  { a: 'оканчиваются на 5', b: 'делятся на 15', A: n => n % 10 === 5, B: n => n % 15 === 0 }
];
reg('logic', 'log_counter', d => {
  const P = R.pick(IMPL);
  const pool = Array.from({ length: 95 }, (_, i) => i + 4);
  const ce = R.shuffle(pool.filter(n => P.A(n) && !P.B(n)));
  const good = R.shuffle(pool.filter(n => P.A(n) && P.B(n)));
  const notA = R.shuffle(pool.filter(n => !P.A(n)));
  if (!ce.length || good.length < 2) return null;
  const right = ce[0];
  const dis = d === 1 ? [good[0], good[1], good[2]] : [good[0], good[1], notA[0]];
  return { q: `Какое число <b>опровергает</b> утверждение:<br><b>«Все числа, которые ${P.a}, ${P.b}»</b>?`, type: 'choice',
    options: choices(right, dis), answer: fmt(right), hint: `Контрпример должен ${P.a.replace(/ятся/, 'иться').replace(/ются/, 'ться').replace('больше', 'быть больше')} — но при этом НЕ ${P.b}.`,
    explain: [`Контрпример — число, для которого условие выполняется, а вывод — нет.`, `${right}: ${P.a.replace(/ятся/, 'ится').replace(/ются/, 'ется')} ✓, но не ${P.b.replace(/ятся/, 'ится').replace(/ются/, 'ется')} ✗.`]
      .concat(d > 1 ? [`Число ${notA[0]} вообще не ${P.a.replace(/ятся/, 'ится').replace(/ются/, 'ется')} — оно ничего не опровергает.`] : []) };
});

