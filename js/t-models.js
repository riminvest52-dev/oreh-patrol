/* ---------- Пещера уравнений ---------- */
const COMP = {
  '+': { name: 'неизвестное слагаемое', rule: 'из суммы вычитаем известное слагаемое' },
  '-L': { name: 'неизвестное уменьшаемое', rule: 'к разности прибавляем вычитаемое' },
  '-R': { name: 'неизвестное вычитаемое', rule: 'из уменьшаемого вычитаем разность' },
  '*': { name: 'неизвестный множитель', rule: 'произведение делим на известный множитель' },
  ':L': { name: 'неизвестное делимое', rule: 'частное умножаем на делитель' },
  ':R': { name: 'неизвестный делитель', rule: 'делимое делим на частное' }
};
function buildEq(steps) {
  for (let tries = 0; tries < 100; tries++) {
    const x = R.int(2, steps > 1 ? 30 : 99);
    let cur = x, s = 'x', lastOp = null; const chain = [];
    let ok = true;
    for (let i = 0; i < steps; i++) {
      const op = R.pick(['+', '-', '*', ':']), xLeft = R.chance(0.6);
      let num, res;
      if (op === '+') { num = R.int(3, 60); res = cur + num; }
      else if (op === '-') { if (xLeft) { num = R.int(2, Math.max(2, cur - 1)); res = cur - num; if (res <= 0) { ok = false; break; } } else { res = R.int(2, 40); num = cur + res; } }
      else if (op === '*') { num = R.int(2, 9); res = cur * num; }
      else { if (xLeft) { const ds = divisors(cur).filter(v => v >= 2 && v <= 9 && v < cur); if (!ds.length) { ok = false; break; } num = R.pick(ds); res = cur / num; } else { res = R.int(2, 9); num = cur * res; } }
      if (res > 2000 || num > 2000) { ok = false; break; }
      const needBr = lastOp && (PREC[op] > PREC[lastOp] || (!xLeft && PREC[op] === PREC[lastOp]));
      const inner = needBr ? `(${s})` : s;
      s = xLeft ? `${inner} ${SYM[op]} ${num}` : `${num} ${SYM[op]} ${inner}`;
      chain.push({ op, xLeft, num, prevStr: inner.replace(/^\((.*)\)$/, '$1'), prev: cur, res });
      cur = res; lastOp = op;
    }
    if (!ok) continue;
    return { x, eq: `${s} = ${cur}`, chain, rhs: cur };
  }
  return null;
}
function eqExplain(E) {
  const out = [];
  for (let i = E.chain.length - 1; i >= 0; i--) {
    const c = E.chain[i], key = c.op === '+' || c.op === '*' ? c.op : c.op + (c.xLeft ? 'L' : 'R');
    const comp = COMP[key];
    let f;
    if (key === '+') f = `${c.res} − ${c.num}`; else if (key === '-L') f = `${c.res} + ${c.num}`; else if (key === '-R') f = `${c.num} − ${c.res}`;
    else if (key === '*') f = `${c.res} : ${c.num}`; else if (key === ':L') f = `${c.res} · ${c.num}`; else f = `${c.num} : ${c.res}`;
    out.push(`<b>${c.prevStr}</b> — ${comp.name}: ${comp.rule}. ${c.prevStr} = ${f} = ${c.prev}`);
  }
  out.push(`Ответ: x = ${E.x}`);
  return out;
}
/* Типичная ошибка: обратное действие перепутано. Для уравнения в одно действие */
function eqWrong(E) {
  const c = E.chain[0], key = c.op === '+' || c.op === '*' ? c.op : c.op + (c.xLeft ? 'L' : 'R');
  if (E.chain.length !== 1) return null;
  return { v: { '+': c.res + c.num, '-L': c.res - c.num, '-R': c.num + c.res, '*': c.res * c.num, ':L': c.res, ':R': c.num * c.res }[key],
    msg: `Здесь x — ${COMP[key].name}: ${COMP[key].rule}.` };
}
reg('eq', 'eq_simple', d => {
  const E = buildEq(d); if (!E) return null;
  const w = eqWrong(E);
  return { q: `Реши уравнение:<br><span class="ex">${E.eq}</span>`, type: 'num', answer: E.x, traps: w ? [w] : [],
    hint: d === 1 ? 'Как называется x в этом уравнении: слагаемое, вычитаемое, множитель, делитель…? Вспомни правило.' : 'Начинай «снаружи»: что выполняется последним? Всё, что внутри, — неизвестный компонент.',
    explain: eqExplain(E) };
});
reg('eq', 'eq_root', d => {
  const E = buildEq(Math.min(d, 2) + (d === 3 ? 1 : 0)); if (!E) return null;
  const c = E.chain[0], key = c.op === '+' || c.op === '*' ? c.op : c.op + (c.xLeft ? 'L' : 'R');
  const wrong = E.chain.length === 1 ? { '+': c.res + c.num, '-L': c.res - c.num, '-R': c.num + c.res, '*': c.res * c.num, ':L': c.res, ':R': c.num * c.res }[key] : E.x * 2;
  const sub = E.eq.split(' = ')[0].replace(/x/g, String(E.x));
  const r = schoolSteps(sub);
  return { q: `Какое число является корнем уравнения?<br><span class="ex">${E.eq}</span>`, type: 'choice',
    options: choices(E.x, [wrong, E.x + 1, E.x - 1, E.x + 2, E.x + 10]), answer: fmt(E.x), hint: 'Подставь каждое число вместо x и проверь, получится ли верное равенство.',
    explain: [`Подставляем x = ${E.x}: ${sub}`].concat(r.steps.map((s, i) => `${i + 1}) ${s}`), [`Получилось ${E.rhs} — равенство верное ✓`]) };
});

